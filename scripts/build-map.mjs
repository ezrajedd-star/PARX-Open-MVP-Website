/**
 * Generates components/map/ph-map-data.ts: a coastline path for the central and
 * southern Philippines (Natural Earth 10m land, public domain, via world-atlas),
 * pre-projected to SVG coordinates. Run once: npm run map
 * The site never loads map tiles or third-party scripts.
 */
import fs from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-10m.json");
const land = feature(topo, topo.objects.land);

// Region shown: Panay → Leyte (W–E), Masbate → Northern Mindanao (N–S).
export const BBOX = { west: 121.7, east: 126.3, south: 7.4, north: 12.6 };
const lat0 = ((BBOX.north + BBOX.south) / 2) * (Math.PI / 180);
const W = 600;
const kx = W / ((BBOX.east - BBOX.west) * Math.cos(lat0));
const H = Math.round((BBOX.north - BBOX.south) * kx);
const project = ([lng, lat]) => [((lng - BBOX.west) * Math.cos(lat0)) * kx, (BBOX.north - lat) * kx];

const pad = 1.5; // degrees of slack so coastlines run off the edge cleanly
const inBox = ([lng, lat]) => lng > BBOX.west - pad && lng < BBOX.east + pad && lat > BBOX.south - pad && lat < BBOX.north + pad;

// Douglas–Peucker simplification (tolerance in px) keeps the file small without visible loss.
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [i, j] = stack.pop();
    const [ax, ay] = pts[i], [bx, by] = pts[j];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy);
    let max = 0, idx = -1;
    for (let k = i + 1; k < j; k++) {
      // Closed rings start and end on the same point: fall back to plain distance.
      const dist = len ? Math.abs(dy * pts[k][0] - dx * pts[k][1] + bx * ay - by * ax) / len : Math.hypot(pts[k][0] - ax, pts[k][1] - ay);
      if (dist > max) { max = dist; idx = k; }
    }
    if (max > tol && idx > 0) { keep[idx] = 1; stack.push([i, idx], [idx, j]); }
  }
  return pts.filter((_, k) => keep[k]);
}

let d = "";
let points = 0;
for (const poly of land.features[0].geometry.coordinates) {
  for (const ring of poly) {
    if (!ring.some(inBox)) continue;
    const pts = simplify(ring.map(project), 0.7).map(([x, y]) => [Math.round(x), Math.round(y)]);
    // Drop specks smaller than ~3px across.
    const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
    if (Math.max(...xs) - Math.min(...xs) < 3 && Math.max(...ys) - Math.min(...ys) < 3) continue;
    let seg = `M${pts[0][0]} ${pts[0][1]}`;
    let n = 1;
    for (let k = 1; k < pts.length; k++) {
      const dx = pts[k][0] - pts[k - 1][0], dy = pts[k][1] - pts[k - 1][1];
      if (!dx && !dy) continue;
      seg += `l${dx} ${dy}`.replace(/ -/g, "-");
      n++;
    }
    if (n >= 4) { d += seg + "z"; points += n; }
  }
}

const out = `/* Generated by scripts/build-map.mjs — do not edit. Natural Earth 10m land (public domain). */
export const MAP_W = ${W};
export const MAP_H = ${H};
export const MAP_BBOX = ${JSON.stringify(BBOX)};
const LAT0 = ${lat0};
const K = ${kx};
/** Project [lng, lat] to map SVG coordinates. */
export function projectLngLat(lng: number, lat: number): [number, number] {
  return [(lng - MAP_BBOX.west) * Math.cos(LAT0) * K, (MAP_BBOX.north - lat) * K];
}
export const LAND_PATH = ${JSON.stringify(d)};
`;
fs.mkdirSync("components/map", { recursive: true });
fs.writeFileSync("components/map/ph-map-data.ts", out);
console.log(`map ${W}x${H}, ${points} points, ${(d.length / 1024).toFixed(1)} KB`);
